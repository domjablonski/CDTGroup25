@pytest.mark.parametrize("module,func,params",
                         [(m, f, p) for m, fs in SIGNATURES.items() for f, p in fs.items()])
def test_signature(module, func, params):
    f = getattr(importlib.import_module(f"foodcom.{module}"), func)
    assert list(inspect.signature(f).parameters) == params


def test_config_constants():
    assert config.SEED == 42 and config.SAMPLE_FRAC == 0.01
    assert len(config.NUTRITION_COLS) == 7 and config.NUTRITION_COLS[0] == "calories"
    assert config.CALORIE_LEVELS == 3 and config.DUPLICATE_JACCARD == 0.9
    for path in (config.RECIPES, config.INTERACTIONS, config.DUPLICATES, config.NEIGHBOURS,
                 config.PAIRS, config.RULES):
        assert path.parent == config.DATA_PROCESSED and path.suffix == ".parquet"


def test_cleaned_data_follow_the_schemas(mini_recipes, mini_interactions):
    schemas.validate(mini_recipes, "recipes")
    schemas.validate(mini_interactions, "interactions")
    assert len(mini_recipes) == 8 and len(mini_interactions) == 12


def test_validate_rejects_missing_columns(mini_recipes):
    with pytest.raises(ValueError, match="cuisine"):
        schemas.validate(mini_recipes.drop(columns="cuisine"), "recipes")
